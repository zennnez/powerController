#!/system/bin/sh

case "$0" in
    */*) MODDIR=${0%/*} ;;
    *) MODDIR=. ;;
esac
. "$MODDIR/power-data.sh"

load_power_data

POWER_PROFILE=$(sed -n 's/^ *"power_profile": "\(.*\)",$/\1/p' "$POWER_STATUS_JSON" 2>/dev/null | head -n 1)
[ -z "$POWER_PROFILE" ] && POWER_PROFILE="N/A"

printf '%s\n' \
    "MODE=$MODE" \
    "CHARGE_LIMIT=$CHARGE_LIMIT" \
    "UPPER_LIMIT=$UPPER_LIMIT" \
    "LOWER_LIMIT=$LOWER_LIMIT" \
    "THERMAL_GUARD=$THERMAL_GUARD" \
    "MAX_TEMP=$MAX_TEMP" \
    "OVERRIDE_MODE=$OVERRIDE_MODE" \
    "FAST_CHARGE=$FAST_CHARGE" \
    "SMART_POWER=$SMART_POWER" \
    "FAST_CHARGE_STATE=$FAST_CHARGE_STATE" \
    "COOL_DOWN=$COOL_DOWN" \
    "POWER_PROFILE=$POWER_PROFILE" \
    "CAPACITY=$CAPACITY" \
    "BATTERY_STATUS=$BATTERY_STATUS" \
    "USB_ONLINE=$USB_ONLINE" \
    "USB_TYPE=$USB_TYPE" \
    "VOLTAGE_NOW=$VOLTAGE_NOW" \
    "CURRENT_NOW_RAW=$CURRENT_NOW_RAW" \
    "CURRENT_NOW_MA=$CURRENT_NOW_MA" \
    "CURRENT_NOW_SOURCE=$CURRENT_NOW_SOURCE" \
    "TEMPERATURE=$TEMPERATURE" \
    "WATTAGE=$WATTAGE" \
    "BYPASS_ENABLED=$BYPASS_ENABLED" \
    "NODE_WRITABLE=$NODE_WRITABLE" \
    "CONTROLLER_STATE=$CONTROLLER_STATE"
